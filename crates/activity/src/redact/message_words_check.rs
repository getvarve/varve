//! Regenerates and checks `message_words.rs`, the words of the servers'
//! message templates (see [`super::message::drop_literals`]).
//!
//! The words come from the English message templates of the servers:
//!
//! - PostgreSQL: the `postgres` binary (13 and 18). Its printable runs of
//!   ten bytes or more that read as a message template (lower-case start,
//!   letters, spaces and punctuation only, at least two spaces, and a `%`
//!   placeholder or at least three spaces).
//! - MySQL 8.0 and 8.4, MariaDB 12.3: `share/english/errmsg.sys`, every
//!   printable run of eight bytes or more.
//!
//! Words are runs of ASCII letters of three or more, in lower case.
//!
//! To refresh the list, copy the files into one directory (any names; a
//! file ending in `.sys` is read as an `errmsg.sys`, any other file as a
//! `postgres` binary), for example from the M2 test servers:
//!
//! ```text
//! mkdir /tmp/catalogs && cd /tmp/catalogs
//! docker cp <postgres-13>:/usr/local/bin/postgres pg13
//! docker cp <postgres-18>:/usr/local/bin/postgres pg18
//! docker cp <mysql-8.0>:/usr/share/mysql-8.0/english/errmsg.sys my80.sys
//! docker cp <mysql-8.4>:/usr/share/mysql-8.4/english/errmsg.sys my84.sys
//! docker cp <mariadb-12.3>:/usr/share/mariadb/english/errmsg.sys maria.sys
//! ```
//!
//! then run
//!
//! ```text
//! VARVE_MESSAGE_CATALOGS=/tmp/catalogs cargo test -p varve-activity \
//!     message_words_match_the_server_catalogs -- --ignored
//! ```
//!
//! which fails when the list differs, or, with `VARVE_REGENERATE=1` also
//! set, writes `src/redact/message_words.rs` anew.

use std::collections::BTreeSet;
use std::path::Path;

use super::message_words::MESSAGE_WORDS;

/// The printable ASCII runs of `bytes` (tab included) of at least `min`
/// bytes.
fn printable_runs(bytes: &[u8], min: usize) -> Vec<String> {
    let mut runs = Vec::new();
    let mut start = 0;
    for (i, &b) in bytes.iter().chain(std::iter::once(&0u8)).enumerate() {
        let printable = (0x20..=0x7e).contains(&b) || b == b'\t';
        if !printable {
            if i - start >= min {
                runs.push(String::from_utf8_lossy(&bytes[start..i]).into_owned());
            }
            start = i + 1;
        }
    }
    runs
}

/// True for a printable run that reads as a PostgreSQL message template.
fn template_like(run: &str) -> bool {
    let mut chars = run.chars();
    let first_ok = chars.next().is_some_and(|c| c.is_ascii_lowercase());
    let rest_ok = run.chars().skip(1).all(|c| {
        c.is_ascii_lowercase()
            || matches!(
                c,
                ' ' | ',' | '%' | '"' | '\'' | '(' | ')' | ':' | ';' | '.' | '/' | '_' | '-'
            )
    });
    let spaces = run.matches(' ').count();
    first_ok && rest_ok && spaces >= 2 && (run.contains('%') || spaces >= 3)
}

fn add_words(text: &str, words: &mut BTreeSet<String>) {
    for word in text.split(|c: char| !c.is_ascii_alphabetic()) {
        if word.len() >= 3 {
            words.insert(word.to_ascii_lowercase());
        }
    }
}

/// The words of every catalog file in `dir`.
fn catalog_words(dir: &Path) -> Result<BTreeSet<String>, Box<dyn std::error::Error>> {
    let mut words = BTreeSet::new();
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        let bytes = std::fs::read(&path)?;
        if path.extension().is_some_and(|e| e == "sys") {
            for run in printable_runs(&bytes, 8) {
                add_words(&run, &mut words);
            }
        } else {
            for run in printable_runs(&bytes, 10) {
                if template_like(&run) {
                    add_words(&run, &mut words);
                }
            }
        }
    }
    Ok(words)
}

/// The source of `message_words.rs` for `words`.
fn render(words: &BTreeSet<String>) -> String {
    let mut out = String::from(
        "//! Words of the server message templates of PostgreSQL 13 and 18 (the\n\
         //! English error messages in the `postgres` binary), MySQL 8.0 and 8.4 and\n\
         //! MariaDB 12.3 (`share/english/errmsg.sys`), lower case, three letters or\n\
         //! more, sorted. Generated by `message_words_check.rs`; do not edit by hand.\n\
         \n\
         /// The template words, sorted for binary search.\n\
         pub(crate) const MESSAGE_WORDS: &[&str] = &[\n",
    );
    for word in words {
        out.push_str(&format!("    \"{word}\",\n"));
    }
    out.push_str("];\n");
    out
}

#[test]
fn message_words_are_sorted_lower_case_words() {
    assert!(MESSAGE_WORDS.windows(2).all(|pair| pair[0] < pair[1]));
    assert!(
        MESSAGE_WORDS
            .iter()
            .all(|w| w.len() >= 3 && w.bytes().all(|b| b.is_ascii_lowercase()))
    );
}

#[test]
#[ignore = "needs the server catalogs: see the module docs"]
fn message_words_match_the_server_catalogs() -> Result<(), Box<dyn std::error::Error>> {
    let dir = std::env::var("VARVE_MESSAGE_CATALOGS")?;
    let words = catalog_words(Path::new(&dir))?;
    if std::env::var("VARVE_REGENERATE").is_ok_and(|v| v == "1") {
        let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/redact/message_words.rs");
        std::fs::write(target, render(&words))?;
        return Ok(());
    }
    let current: BTreeSet<String> = MESSAGE_WORDS.iter().map(|w| (*w).to_string()).collect();
    let missing: Vec<&String> = words.difference(&current).collect();
    let extra: Vec<&String> = current.difference(&words).collect();
    assert!(
        missing.is_empty() && extra.is_empty(),
        "missing {missing:?}, extra {extra:?}"
    );
    Ok(())
}
