//! Input and output types of grid data editing, shaped for the UI
//! (`camelCase` JSON).

use serde::{Deserialize, Serialize};
use varve_core::Engine;
use varve_driver::{DriverError, Value};

/// The table whose rows are edited.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TableTarget {
    /// Database: the PostgreSQL database the session is connected to, or
    /// the MySQL / MariaDB database (schema) that holds the table.
    pub database: String,
    /// PostgreSQL schema. Required for PostgreSQL, must be `None` for
    /// MySQL and MariaDB.
    pub schema: Option<String>,
    /// Table name.
    pub table: String,
}

/// Identifies one row: the values of every column of the table's primary
/// key, or of a unique key whose columns are all `NOT NULL` (see
/// [`KeyInfo`]).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RowKey {
    /// `(column, value)` for every key column. Values are never `NULL`.
    pub columns: Vec<(String, Value)>,
}

/// What a grid cell holds for an insert or update.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "kind", content = "value", rename_all = "camelCase")]
pub enum CellValue {
    /// A value, written as a literal of the column's type.
    Value(Value),
    /// The column's default (`DEFAULT`).
    Default,
    /// Raw SQL the user typed into the cell, flagged in the UI. It must be
    /// one self-contained expression: balanced parentheses, closed quotes,
    /// no comments and no `;`.
    Expression(String),
}

/// One change made in the grid.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "op", rename_all = "camelCase")]
pub enum RowChange {
    /// A new row. Columns that are left out get their default.
    Insert {
        /// `(column, value)` for the columns the user filled in.
        values: Vec<(String, CellValue)>,
    },
    /// Changed cells of an existing row.
    Update {
        /// The row's key as it was read.
        key: RowKey,
        /// `(column, value)` as the row was read. With
        /// [`PlanOptions::check_original`] it must hold every column in
        /// `set`.
        original: Vec<(String, Value)>,
        /// `(column, value)` for the changed cells.
        set: Vec<(String, CellValue)>,
    },
    /// A deleted row.
    Delete {
        /// The row's key as it was read.
        key: RowKey,
        /// `(column, value)` as the row was read. With
        /// [`PlanOptions::check_original`] every column listed here must
        /// still hold its value.
        original: Vec<(String, Value)>,
    },
}

/// Which kind of key identifies rows.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum KeyKind {
    /// The primary key.
    Primary,
    /// A unique constraint or index whose columns are all `NOT NULL`.
    Unique,
}

/// How a generated column is computed.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum GeneratedKind {
    /// Computed when written and stored.
    Stored,
    /// Computed when read (PostgreSQL 18, MySQL, MariaDB).
    Virtual,
}

/// A PostgreSQL identity column.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum IdentityKind {
    /// `GENERATED ALWAYS AS IDENTITY`: the server always assigns it.
    Always,
    /// `GENERATED BY DEFAULT AS IDENTITY`: assigned unless a value is given.
    ByDefault,
}

/// A column of the edited table, with what literals and the UI need.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ColumnInfo {
    /// Column name.
    pub name: String,
    /// Type for display: PostgreSQL `format_type` (`character varying(20)`,
    /// `integer[]`), MySQL / MariaDB `COLUMN_TYPE` (`int unsigned`).
    pub data_type: String,
    /// PostgreSQL: schema of the column's type (`pg_catalog`, or the schema
    /// of an enum or domain). `None` for MySQL and MariaDB.
    pub type_schema: Option<String>,
    /// PostgreSQL: the type's own name (`int4`, `_text`, `mood`), used to
    /// cast literals without a type modifier. MySQL / MariaDB: `DATA_TYPE`
    /// in lower case (`float`, `json`, `varchar`).
    pub type_name: String,
    /// PostgreSQL: for a domain column, the schema and name of the type it
    /// is based on, through every domain level (`pg_catalog`, `xml`).
    /// `None` for other columns and for MySQL / MariaDB.
    #[serde(default)]
    pub base_type: Option<(String, String)>,
    /// PostgreSQL: true when the column's type, or the base type of its
    /// domain, is an array. False for MySQL / MariaDB.
    #[serde(default)]
    pub array: bool,
    /// PostgreSQL: true when the column is an array whose element type is
    /// a domain over an array (`d[]` with `CREATE DOMAIN d AS int[]`). The
    /// client reads such a value as nested arrays without telling element
    /// arrays from dimensions, so Varve cannot write it back as a literal:
    /// the column is not editable, it is left out of the original-value
    /// check (with a warning in the plan), and a key over it is refused.
    /// False for MySQL / MariaDB.
    #[serde(default)]
    pub array_of_arrays: bool,
    /// True when the column accepts `NULL`.
    pub nullable: bool,
    /// True when the server fills the column when it is left out (a
    /// default, an identity, an auto-increment or a generated column).
    pub has_default: bool,
    /// Set for generated columns.
    pub generated: Option<GeneratedKind>,
    /// Set for PostgreSQL identity columns.
    pub identity: Option<IdentityKind>,
    /// MySQL / MariaDB `AUTO_INCREMENT`.
    pub auto_increment: bool,
    /// False when the grid must not let the user write the column:
    /// generated columns and `GENERATED ALWAYS` identity columns.
    pub editable: bool,
}

/// The key that makes a table editable, plus the columns of the table.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct KeyInfo {
    /// Primary or unique.
    pub kind: KeyKind,
    /// Constraint name, or the index name for a unique index without a
    /// constraint (MySQL `PRIMARY` for primary keys).
    pub name: String,
    /// Key columns, in key order.
    pub columns: Vec<String>,
    /// Every column of the table, in table order.
    pub table_columns: Vec<ColumnInfo>,
    /// PostgreSQL: the equality operator of every key column, in key
    /// order, as the key's unique index defines it (the `=` of the index
    /// operator class). Rows are found with `column OPERATOR(schema.op)
    /// value` so the operator cannot be taken over by one with the same
    /// name earlier in the user's `search_path`. Empty for MySQL and
    /// MariaDB.
    #[serde(default)]
    pub equality_operators: Vec<QualifiedOperator>,
    /// PostgreSQL: the collation of the key's unique index for every key
    /// column, in key order (`None` for a type without collation). Keys are
    /// compared in it, so a case-insensitive column with a unique index in
    /// `"C"` finds exactly the row the index tells apart. Empty for MySQL
    /// and MariaDB, and accepted empty for PostgreSQL (no collation then).
    #[serde(default)]
    pub key_collations: Vec<Option<KeyCollation>>,
}

/// A collation named with its schema.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct KeyCollation {
    /// Schema of the collation.
    pub schema: String,
    /// Collation name (`C`, `und-x-icu`).
    pub name: String,
}

/// An operator named with its schema, as `OPERATOR(schema.name)` writes it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct QualifiedOperator {
    /// Schema of the operator (`pg_catalog` for built-in types).
    pub schema: String,
    /// Operator name (`=`).
    pub name: String,
}

impl KeyInfo {
    /// The column with this name. PostgreSQL names match exactly. MySQL
    /// and MariaDB column names are case-insensitive, so with
    /// `case_insensitive` a match ignoring case is accepted when there is
    /// no exact one.
    #[must_use]
    pub fn column(&self, name: &str, case_insensitive: bool) -> Option<&ColumnInfo> {
        self.table_columns
            .iter()
            .find(|c| c.name == name)
            .or_else(|| {
                if case_insensitive {
                    let lower = name.to_lowercase();
                    self.table_columns
                        .iter()
                        .find(|c| c.name.to_lowercase() == lower)
                } else {
                    None
                }
            })
    }
}

/// Options for [`crate::data_edit::plan_edits`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanOptions {
    /// Optimistic concurrency: an update also requires the changed columns
    /// to still hold their original values, and a delete every original
    /// value it lists, so a row someone else changed is not overwritten.
    pub check_original: bool,
    /// The table's key and column types, from
    /// [`crate::data_edit::editable_key`].
    pub key: KeyInfo,
}

/// What a planned change does.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ChangeOp {
    /// `INSERT`.
    Insert,
    /// `UPDATE`.
    Update,
    /// `DELETE`.
    Delete,
}

/// The SQL for one [`RowChange`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlannedChange {
    /// Index of the change in the list given to the planner.
    pub change: usize,
    /// What it does.
    pub op: ChangeOp,
    /// MySQL / MariaDB updates: `SELECT ... FOR UPDATE` that locks the row
    /// and must return exactly one row. Needed because MySQL reports
    /// changed rows, not matched rows, for an `UPDATE`.
    pub lock: Option<String>,
    /// The `INSERT`, `UPDATE` or `DELETE`.
    pub statement: String,
    /// True when the statement itself returns the written row
    /// (`RETURNING *`).
    pub returns_row: bool,
    /// MySQL / MariaDB: `SELECT` that reads the written row back. `None`
    /// for deletes, when the statement returns the row, or when the row
    /// cannot be found again (a key column set by an expression or a
    /// non-auto-increment default; [`RowEditPlan::warnings`] says so).
    pub refresh: Option<String>,
    /// True when the statement also compares original values.
    pub checks_original: bool,
}

/// The SQL for a set of grid changes, shown to the user and then run by
/// [`crate::data_edit::apply`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RowEditPlan {
    /// Engine the SQL is written for.
    pub engine: Engine,
    /// The changes, in order.
    pub changes: Vec<PlannedChange>,
    /// Notes for the user (rows that cannot be read back).
    pub warnings: Vec<String>,
    /// True when a cell holds raw SQL ([`CellValue::Expression`]).
    pub has_expressions: bool,
}

impl RowEditPlan {
    /// The whole script as it runs, for the preview: transaction start,
    /// every statement with its `;`, and `COMMIT`.
    #[must_use]
    pub fn script(&self) -> String {
        let begin = match self.engine {
            Engine::Postgres => "BEGIN",
            _ => "START TRANSACTION",
        };
        let mut out = format!("{begin};\n");
        for change in &self.changes {
            for sql in change
                .lock
                .iter()
                .chain(std::iter::once(&change.statement))
                .chain(change.refresh.iter())
            {
                out.push_str(sql);
                out.push_str(";\n");
            }
        }
        out.push_str("COMMIT;\n");
        out
    }
}

/// Why a change could not be applied as planned.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ConflictReason {
    /// No row matched: someone else deleted the row or changed its key,
    /// or (with original value checks) changed one of the compared values.
    RowChanged,
    /// More than one row matched the key, so it does not identify a row.
    KeyNotUnique,
}

/// A row written by an applied change, as the server stored it.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct AppliedChange {
    /// Index of the change.
    pub change: usize,
    /// What it did.
    pub op: ChangeOp,
    /// `(column, value)` of the row after the change, with defaults and
    /// generated values filled in. `None` for deletes and for rows the
    /// plan cannot read back ([`PlannedChange::refresh`]).
    pub row: Option<Vec<(String, Value)>>,
}

/// The result of [`crate::data_edit::apply`]. Only [`ApplyOutcome::Applied`]
/// changed anything: the other outcomes rolled everything back.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "status", rename_all = "camelCase")]
pub enum ApplyOutcome {
    /// Every change was applied and committed.
    #[serde(rename_all = "camelCase")]
    Applied {
        /// One entry per change, in order.
        rows: Vec<AppliedChange>,
    },
    /// A change did not match exactly one row; nothing was applied.
    #[serde(rename_all = "camelCase")]
    Conflict {
        /// Index of the change.
        change: usize,
        /// Why.
        reason: ConflictReason,
        /// Rows the change matched (0, or more than 1).
        rows_matched: u64,
        /// Message for the user.
        message: String,
    },
    /// The server rejected a change (a constraint, a type error, a
    /// trigger, ...); nothing was applied.
    #[serde(rename_all = "camelCase")]
    Failed {
        /// Index of the change.
        change: usize,
        /// The server's error.
        error: DriverError,
    },
}
