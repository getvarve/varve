/// How a partition is detached.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(rename_all = "camelCase")]
pub enum DetachMode {
    /// Plain: takes an ACCESS EXCLUSIVE lock on the parent.
    #[default]
    Normal,
    /// `CONCURRENTLY` (14+): does not block queries on the parent, cannot
    /// run in a transaction.
    Concurrently,
    /// `FINALIZE` (14+): completes an interrupted concurrent detach.
    Finalize,
}

/// One operation of `ALTER TABLE`. Operations run in order, one statement
/// each, so later operations see the effect of earlier ones (a rename
