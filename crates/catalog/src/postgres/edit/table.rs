/// The kind of a table constraint and its definition.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(
    tag = "type",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum ConstraintKind {
    /// `PRIMARY KEY`.
    PrimaryKey {
        /// Key columns.
        columns: Vec<String>,
        /// `INCLUDE` columns.
        #[serde(default)]
        include: Vec<String>,
        /// Storage parameters of the index.
        #[serde(default)]
        storage_params: Vec<StorageParam>,
        /// Tablespace of the index.
        #[serde(default)]
        index_tablespace: Option<String>,
    },
    /// `UNIQUE`.
    Unique {
        /// Key columns.
        columns: Vec<String>,
        /// `INCLUDE` columns.
        #[serde(default)]
        include: Vec<String>,
        /// `NULLS NOT DISTINCT` (15+).
        #[serde(default)]
        nulls_not_distinct: bool,
        /// Storage parameters of the index.
        #[serde(default)]
        storage_params: Vec<StorageParam>,
        /// Tablespace of the index.
        #[serde(default)]
        index_tablespace: Option<String>,
    },
    /// `CHECK`.
    Check {
        /// The condition, without parentheses.
        expression: String,
        /// `NO INHERIT`: not inherited by child tables.
        #[serde(default)]
        no_inherit: bool,
    },
    /// `EXCLUDE`.
    Exclusion {
        /// Access method (GiST when absent).
        #[serde(default)]
        method: Option<IndexMethod>,
        /// Elements and operators.
        elements: Vec<ExclusionElement>,
        /// `INCLUDE` columns.
        #[serde(default)]
        include: Vec<String>,
        /// Storage parameters of the index.
        #[serde(default)]
        storage_params: Vec<StorageParam>,
        /// Tablespace of the index.
        #[serde(default)]
        index_tablespace: Option<String>,
        /// `WHERE` predicate: only rows matching it are checked.
        #[serde(default)]
        predicate: Option<String>,
    },
    /// `FOREIGN KEY`.
    ForeignKey {
        /// Referencing columns.
        columns: Vec<String>,
        /// Referenced table.
        references: QualifiedName,
        /// Referenced columns; empty uses the referenced primary key.
        #[serde(default)]
        referenced_columns: Vec<String>,
        /// `MATCH`.
        #[serde(default)]
        match_type: Option<MatchType>,
        /// `ON DELETE`.
        #[serde(default)]
        on_delete: Option<ReferentialAction>,
        /// `ON UPDATE`.
        #[serde(default)]
        on_update: Option<ReferentialAction>,
    },
}

/// A table constraint.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(rename_all = "camelCase")]
pub struct TableConstraint {
    /// Name; `None` lets PostgreSQL choose one.
    #[serde(default)]
    pub name: Option<String>,
    /// Kind and definition, tagged by `type`.
    pub kind: ConstraintKind,
    /// `DEFERRABLE` (not for checks).
    #[serde(default)]
    pub deferrable: bool,
    /// `INITIALLY DEFERRED` (needs `deferrable`).
    #[serde(default)]
    pub initially_deferred: bool,
}

impl TableConstraint {
    /// A constraint without name or deferral.
    #[must_use]
    pub fn new(kind: ConstraintKind) -> Self {
        Self {
            name: None,
            kind,
            deferrable: false,
            initially_deferred: false,
        }
    }

    fn sql(&self, server: &ServerInfo) -> CatalogResult<String> {
        let mut s = String::new();
        if let Some(name) = &self.name {
            s.push_str(&format!("CONSTRAINT {} ", ident(name)?));
        }
        let index_tail = |include: &str,
                          params: &[StorageParam],
                          ts: &Option<String>|
         -> CatalogResult<String> {
            let mut t = include.to_owned();
            if !params.is_empty() {
                t.push_str(&format!(" WITH ({})", storage_params(params)?));
            }
            if let Some(ts) = ts {
                t.push_str(&format!(" USING INDEX TABLESPACE {}", ident(ts)?));
            }
            Ok(t)
        };
        let key_columns = |columns: &[String]| -> CatalogResult<String> {
            if columns.is_empty() {
                return Err(invalid("a key needs at least one column"));
            }
            ident_list(columns)
        };
        match &self.kind {
            ConstraintKind::PrimaryKey {
                columns,
                include,
                storage_params,
                index_tablespace,
            } => {
                s.push_str(&format!("PRIMARY KEY ({})", key_columns(columns)?));
                let inc = include_sql(server, &IndexMethod::Btree, include)?;
                s.push_str(&index_tail(&inc, storage_params, index_tablespace)?);
            }
            ConstraintKind::Unique {
                columns,
                include,
                nulls_not_distinct,
                storage_params,
                index_tablespace,
            } => {
                s.push_str("UNIQUE");
                if *nulls_not_distinct {
                    require(server, 15, "NULLS NOT DISTINCT")?;
                    s.push_str(" NULLS NOT DISTINCT");
                }
                s.push_str(&format!(" ({})", key_columns(columns)?));
                let inc = include_sql(server, &IndexMethod::Btree, include)?;
                s.push_str(&index_tail(&inc, storage_params, index_tablespace)?);
            }
            ConstraintKind::Check {
                expression,
                no_inherit,
            } => {
                if self.deferrable {
                    return Err(invalid("check constraints cannot be deferrable"));
                }
                s.push_str(&format!(
                    "CHECK ({})",
                    expr(expression, "a check expression")?
                ));
                if *no_inherit {
                    s.push_str(" NO INHERIT");
                }
            }
            ConstraintKind::Exclusion {
                method,
                elements,
                include,
                storage_params,
                index_tablespace,
                predicate,
            } => {
                if elements.is_empty() {
                    return Err(invalid(
                        "an exclusion constraint needs at least one element",
                    ));
                }
                let method = method.clone().unwrap_or(IndexMethod::Gist);
                let parts = elements
                    .iter()
                    .map(|e| {
                        Ok(format!(
                            "{} WITH {}",
                            e.element.sql(server, &method)?,
                            operator(&e.operator, e.operator_schema.as_deref())?
                        ))
                    })
                    .collect::<CatalogResult<Vec<_>>>()?;
                s.push_str(&format!(
                    "EXCLUDE USING {} ({})",
                    method.sql()?,
                    parts.join(", ")
                ));
                let inc = include_sql(server, &method, include)?;
                s.push_str(&index_tail(&inc, storage_params, index_tablespace)?);
                if let Some(p) = opt_paren_expr(predicate.as_deref(), "an exclusion predicate")? {
                    s.push_str(&format!(" WHERE {p}"));
                }
            }
            ConstraintKind::ForeignKey {
                columns,
                references,
                referenced_columns,
                match_type,
                on_delete,
                on_update,
            } => {
                s.push_str(&format!(
                    "FOREIGN KEY ({}) REFERENCES {}",
                    key_columns(columns)?,
                    references.sql()?
                ));
                if !referenced_columns.is_empty() {
                    if referenced_columns.len() != columns.len() {
                        return Err(invalid(
                            "a foreign key needs as many referenced columns as referencing columns",
                        ));
                    }
                    s.push_str(&format!(" ({})", ident_list(referenced_columns)?));
                }
                match match_type {
                    Some(MatchType::Simple) => s.push_str(" MATCH SIMPLE"),
                    Some(MatchType::Full) => s.push_str(" MATCH FULL"),
                    None => {}
                }
                if let Some(a) = on_delete {
                    s.push_str(" ON DELETE ");
                    s.push_str(&a.sql(server, true)?);
                }
                if let Some(a) = on_update {
                    s.push_str(" ON UPDATE ");
                    s.push_str(&a.sql(server, false)?);
                }
            }
        }
        if self.initially_deferred && !self.deferrable {
            return Err(invalid("INITIALLY DEFERRED needs DEFERRABLE"));
        }
        if self.deferrable {
            s.push_str(" DEFERRABLE");
            if self.initially_deferred {
                s.push_str(" INITIALLY DEFERRED");
            }
        }
        Ok(s)
    }
}

/// Partitioning strategy.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(rename_all = "camelCase")]
pub enum PartitionStrategy {
    /// `RANGE`.
    Range,
    /// `LIST` (one key).
    List,
    /// `HASH`.
    Hash,
}

/// One partition key column or expression.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(rename_all = "camelCase")]
pub struct PartitionKey {
    /// Column or expression.
    pub key: IndexKey,
    /// `COLLATE`.
    #[serde(default)]
    pub collation: Option<String>,
    /// Operator class.
    #[serde(default)]
    pub opclass: Option<QualifiedName>,
}

/// `PARTITION BY`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(rename_all = "camelCase")]
pub struct PartitionBy {
    /// Strategy.
    pub strategy: PartitionStrategy,
    /// Keys.
    pub keys: Vec<PartitionKey>,
}

impl PartitionBy {
    fn sql(&self) -> CatalogResult<String> {
        if self.keys.is_empty() {
            return Err(invalid(
                "a partition key needs at least one column or expression",
            ));
        }
        if self.strategy == PartitionStrategy::List && self.keys.len() != 1 {
            return Err(invalid("list partitioning takes exactly one key"));
        }
        let keys = self
            .keys
            .iter()
            .map(|k| {
                let mut s = k.key.sql()?;
                if let Some(c) = &k.collation {
                    s.push_str(&format!(" COLLATE {}", ident(c)?));
                }
                if let Some(o) = &k.opclass {
                    s.push_str(&format!(" {}", o.sql()?));
                }
                Ok(s)
            })
            .collect::<CatalogResult<Vec<_>>>()?;
        let strategy = match self.strategy {
            PartitionStrategy::Range => "RANGE",
            PartitionStrategy::List => "LIST",
            PartitionStrategy::Hash => "HASH",
        };
        Ok(format!("PARTITION BY {strategy} ({})", keys.join(", ")))
    }
}

/// A value in a partition bound.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum BoundValue {
    /// `MINVALUE` (range bounds).
    MinValue,
    /// `MAXVALUE` (range bounds).
    MaxValue,
    /// `NULL` (list bounds).
    Null,
    /// A value written as a string literal; PostgreSQL converts it to the
    /// key's type (`'2024-01-01'`, `'10'`).
    Literal {
        /// The value as text.
        value: String,
    },
    /// An expression as SQL.
    Expression {
        /// The expression.
        sql: String,
    },
}

impl BoundValue {
    fn sql(&self, range: bool) -> CatalogResult<String> {
        match self {
            Self::MinValue | Self::MaxValue if !range => Err(invalid(
                "MINVALUE and MAXVALUE are only allowed in range bounds",
            )),
            Self::MinValue => Ok("MINVALUE".into()),
            Self::MaxValue => Ok("MAXVALUE".into()),
            Self::Null if range => Err(invalid("NULL is not allowed in a range bound")),
            Self::Null => Ok("NULL".into()),
            Self::Literal { value } => lit(value),
            Self::Expression { sql } => expr(sql, "a partition bound"),
        }
    }
}

/// The bound of a partition.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(
    tag = "kind",
    rename_all = "camelCase",
    rename_all_fields = "camelCase"
)]
pub enum PartitionBound {
    /// `FOR VALUES FROM (...) TO (...)`.
    Range {
        /// Lower bound (inclusive), one value per key.
        from: Vec<BoundValue>,
        /// Upper bound (exclusive), one value per key.
        to: Vec<BoundValue>,
    },
    /// `FOR VALUES IN (...)`.
    List {
        /// Values.
        values: Vec<BoundValue>,
    },
    /// `FOR VALUES WITH (MODULUS m, REMAINDER r)`.
    Hash {
        /// Modulus.
        modulus: u32,
        /// Remainder, below the modulus.
        remainder: u32,
    },
    /// `DEFAULT`: rows no other partition takes.
    Default,
}

impl PartitionBound {
    fn sql(&self) -> CatalogResult<String> {
        let list = |values: &[BoundValue], range: bool| -> CatalogResult<String> {
            if values.is_empty() {
                return Err(invalid("a partition bound needs at least one value"));
            }
            Ok(values
                .iter()
                .map(|v| v.sql(range))
                .collect::<CatalogResult<Vec<_>>>()?
                .join(", "))
        };
        match self {
            Self::Range { from, to } => {
                if from.len() != to.len() {
                    return Err(invalid("FROM and TO need the same number of values"));
                }
                Ok(format!(
                    "FOR VALUES FROM ({}) TO ({})",
                    list(from, true)?,
                    list(to, true)?
                ))
            }
            Self::List { values } => Ok(format!("FOR VALUES IN ({})", list(values, false)?)),
            Self::Hash { modulus, remainder } => {
                if *modulus == 0 || remainder >= modulus {
                    return Err(invalid(
                        "a hash partition needs a modulus above 0 and a remainder below it",
                    ));
                }
                Ok(format!(
                    "FOR VALUES WITH (MODULUS {modulus}, REMAINDER {remainder})"
                ))
            }
            Self::Default => Ok("DEFAULT".into()),
        }
    }
}

