/// `GENERATED ALWAYS` or `GENERATED BY DEFAULT` for identity columns.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(rename_all = "camelCase")]
pub enum IdentityGeneration {
    /// `ALWAYS`: explicit values need `OVERRIDING SYSTEM VALUE`.
    Always,
    /// `BY DEFAULT`: explicit values are allowed.
    ByDefault,
}

impl IdentityGeneration {
    fn sql(self) -> &'static str {
        match self {
            Self::Always => "ALWAYS",
            Self::ByDefault => "BY DEFAULT",
        }
    }
}

/// An identity column.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[serde(rename_all = "camelCase")]
pub struct Identity {
    /// Always or by default.
    pub generation: IdentityGeneration,
    /// Options of the identity sequence (`data_type` must be absent: the
    /// sequence takes the column's type).
    #[serde(default)]
    pub options: SequenceOptions,
}

impl Identity {
    fn sql(&self) -> CatalogResult<String> {
        if self.options.data_type.is_some() {
            return Err(invalid(
                "an identity sequence takes the column's type; leave the sequence type out",
            ));
        }
        let mut s = format!("GENERATED {} AS IDENTITY", self.generation.sql());
        let options = self.options.sql()?;
        if !options.is_empty() {
            s.push_str(&format!(" ({})", options.join(" ")));
        }
        Ok(s)
    }
}

