    #[test]
    fn constraints_validation_and_partitions() -> CatalogResult<()> {
        let check = TableConstraint {
            name: Some("c".into()),
            ..TableConstraint::new(ConstraintKind::Check {
                expression: "v > 0".into(),
                no_inherit: false,
            })
        };
        let plan = alter(
            &pg(13),
            vec![
                TableOperation::AddConstraint {
                    constraint: check.clone(),
                    not_valid: true,
                },
                TableOperation::ValidateConstraint { name: "c".into() },
                TableOperation::RenameConstraint {
                    name: "c".into(),
                    new_name: "d".into(),
                },
                TableOperation::DropConstraint {
                    name: "d".into(),
                    if_exists: true,
                    behavior: DropBehavior::Restrict,
                },
                TableOperation::AttachPartition {
                    partition: QualifiedName::new("s", "p"),
                    bound: PartitionBound::Default,
                },
                TableOperation::DetachPartition {
                    partition: QualifiedName::new("s", "p"),
                    mode: DetachMode::Normal,
                },
            ],
        )?;
        assert_eq!(
            plan.statements,
            vec![
                r#"ALTER TABLE "s"."t" ADD CONSTRAINT "c" CHECK (v > 0) NOT VALID"#,
                r#"ALTER TABLE "s"."t" VALIDATE CONSTRAINT "c""#,
                r#"ALTER TABLE "s"."t" RENAME CONSTRAINT "c" TO "d""#,
                r#"ALTER TABLE "s"."t" DROP CONSTRAINT IF EXISTS "d" RESTRICT"#,
                r#"ALTER TABLE "s"."t" ATTACH PARTITION "s"."p" DEFAULT"#,
                r#"ALTER TABLE "s"."t" DETACH PARTITION "s"."p""#,
            ]
        );
        assert!(plan.transactional && plan.destructive);

        let fk = TableConstraint::new(ConstraintKind::ForeignKey {
            columns: vec!["a".into()],
            references: QualifiedName::new("s", "o"),
            referenced_columns: vec![],
            match_type: None,
            on_delete: Some(ReferentialAction::Restrict),
            on_update: Some(ReferentialAction::NoAction),
        });
        let fk_plan = alter(
            &pg(13),
            vec![TableOperation::AddConstraint {
                constraint: fk,
                not_valid: false,
            }],
        )?;
        assert_eq!(
            fk_plan.statements,
            vec![
                r#"ALTER TABLE "s"."t" ADD FOREIGN KEY ("a") REFERENCES "s"."o" ON DELETE RESTRICT ON UPDATE NO ACTION"#
            ]
        );
        assert!(
            !fk_plan
                .warnings
                .iter()
                .any(|w| w.starts_with("ALTER TABLE takes"))
        );

        let unique = TableConstraint::new(ConstraintKind::Unique {
            columns: vec!["a".into()],
            include: vec![],
            nulls_not_distinct: false,
            storage_params: vec![],
            index_tablespace: None,
        });
        assert!(
            alter(
                &pg(13),
                vec![TableOperation::AddConstraint {
                    constraint: unique,
                    not_valid: true
                }]
            )
            .is_err()
        );
        assert!(
            TableConstraint {
                deferrable: true,
                ..check.clone()
            }
            .sql(&pg(13))
            .is_err()
        );
        assert!(
            TableConstraint {
                initially_deferred: true,
                ..check
            }
            .sql(&pg(13))
            .is_err()
        );
        assert!(
            ReferentialAction::SetNull {
                columns: vec!["a".into()]
            }
            .sql(&pg(14), true)
            .is_err()
        );
        assert!(
            ReferentialAction::SetNull {
                columns: vec!["a".into()]
            }
            .sql(&pg(15), false)
            .is_err()
        );

        let detach = alter(
            &pg(14),
            vec![TableOperation::DetachPartition {
                partition: QualifiedName::new("s", "p"),
                mode: DetachMode::Concurrently,
            }],
        )?;
        assert_eq!(
            detach.statements,
            vec![r#"ALTER TABLE "s"."t" DETACH PARTITION "s"."p" CONCURRENTLY"#]
        );
        assert!(!detach.transactional);
        let finalize = alter(
            &pg(14),
            vec![TableOperation::DetachPartition {
                partition: QualifiedName::new("s", "p"),
                mode: DetachMode::Finalize,
            }],
        )?;
        assert_eq!(
            finalize.statements,
            vec![r#"ALTER TABLE "s"."t" DETACH PARTITION "s"."p" FINALIZE"#]
        );
        assert!(finalize.transactional);
        // FINALIZE can share a plan; only CONCURRENTLY must run alone.
        let combined = alter(
            &pg(14),
            vec![
                TableOperation::DetachPartition {
                    partition: QualifiedName::new("s", "p"),
                    mode: DetachMode::Finalize,
                },
                TableOperation::RowLevelSecurity { enabled: true },
            ],
        )?;
        assert_eq!(combined.statements.len(), 2);
        assert!(combined.transactional);
        assert!(
            alter(
                &pg(13),
                vec![TableOperation::DetachPartition {
                    partition: QualifiedName::new("s", "p"),
                    mode: DetachMode::Concurrently,
                }]
            )
            .is_err()
        );
        assert!(
            alter(
                &pg(14),
                vec![
                    TableOperation::RowLevelSecurity { enabled: true },
                    TableOperation::DetachPartition {
                        partition: QualifiedName::new("s", "p"),
                        mode: DetachMode::Concurrently,
                    }
                ]
            )
            .is_err()
        );
        Ok(())
    }

